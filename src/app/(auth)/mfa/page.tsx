'use client'
import { useEffect, useState } from 'react'
import { useRouter } from 'next/navigation'
import Link from 'next/link'
import { KeyRound, ShieldCheck, AlertCircle, ArrowLeft } from 'lucide-react'
import { mfaRequest } from '@/features/auth/api'
import { useAuthStore } from '@/stores/auth-store'
import { Input } from '@/components/ui/input'
import { Button } from '@/components/ui/button'

export default function MfaPage(): React.JSX.Element {
  const [code, setCode] = useState('')
  const [err, setErr] = useState('')
  const [attempts, setAttempts] = useState(0)
  const [cooldown, setCooldown] = useState(0)
  const [submitting, setSubmitting] = useState(false)
  const router = useRouter()

  useEffect(() => {
    if (code.length === 6 && !submitting) {
      setSubmitting(true)
      setErr('')
      void (async () => {
        try {
          const r = await mfaRequest(code)
          useAuthStore.getState().setSession(r.user, r.accessToken, r.expiresIn)
          const role = r.user.role
          router.push(role === 'admin' ? '/admin/users' : role === 'approver' ? '/approvals' : '/')
        } catch (e) {
          const n = attempts + 1
          setAttempts(n)
          setErr(e instanceof Error ? e.message : 'Invalid code')
          if (n >= 3) setErr('Too many attempts — account locked for 5 minutes')
          else setCooldown(30)
          setCode('')
        } finally {
          setSubmitting(false)
        }
      })()
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [code])

  useEffect(() => {
    if (cooldown <= 0) return
    const t = setInterval(() => setCooldown((c) => Math.max(0, c - 1)), 1000)
    return () => clearInterval(t)
  }, [cooldown])

  return (
    <div className="flex min-h-[100dvh] items-center justify-center bg-slate-50 p-4 dark:bg-slate-950 transition-colors">
      <main className="w-full max-w-md animate-item-reveal space-y-6">
        <div className="flex flex-col items-center text-center">
          <div className="flex h-12 w-12 items-center justify-center rounded-xl bg-slate-900 text-white dark:bg-slate-800 dark:text-sky-400 mb-3 shadow-sm">
            <KeyRound size={22} />
          </div>
          <span className="font-mono text-[10px] font-semibold uppercase tracking-wider text-slate-500 dark:text-slate-400">
            Cryptographic Verification
          </span>
          <h1 className="mt-1 text-2xl font-bold tracking-tight text-slate-900 dark:text-white font-display">
            Two-factor authentication
          </h1>
          <p className="mt-1 text-xs text-slate-500 dark:text-slate-400 max-w-xs">
            Enter the 6-digit TOTP security code generated by your authenticator hardware key or
            app.
          </p>
        </div>

        <div className="rounded-xl border border-slate-200 bg-white p-7 shadow-sm dark:border-slate-800 dark:bg-slate-900 space-y-4">
          <div>
            <label htmlFor="totp-code" className="sr-only">
              6-digit verification code
            </label>
            <Input
              id="totp-code"
              aria-label="6-digit code"
              inputMode="numeric"
              maxLength={6}
              value={code}
              autoFocus
              placeholder="123 456"
              onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
              className="h-12 text-center font-mono text-xl tracking-[0.4em] font-bold"
            />

            {err ? (
              <div
                role="alert"
                className="mt-2.5 flex items-center gap-1.5 rounded-lg border border-rose-300 bg-rose-50 p-2.5 text-xs text-rose-900 dark:border-rose-900 dark:bg-rose-950 dark:text-rose-200 font-mono"
              >
                <AlertCircle size={14} className="shrink-0 text-rose-600" />
                <span>{err}</span>
              </div>
            ) : null}
          </div>

          <div className="flex items-center justify-between text-xs font-mono text-slate-500">
            <span>Security Threshold:</span>
            <span>Attempts: {attempts}/3</span>
          </div>

          <Button
            disabled={cooldown > 0}
            onClick={() => setCooldown(30)}
            variant="outline"
            className="w-full text-xs"
          >
            {cooldown > 0 ? `Resend code in ${cooldown}s` : 'Resend authentication code'}
          </Button>

          {/* Demo helper */}
          <div className="rounded border border-slate-200 bg-slate-50 p-2 text-center text-xs text-slate-600 dark:border-slate-800 dark:bg-slate-800 dark:text-slate-400">
            <span>Demo bypass code: </span>
            <button
              type="button"
              onClick={() => setCode('123456')}
              className="font-mono font-bold text-sky-700 hover:underline dark:text-sky-400 ml-1"
            >
              123456
            </button>
          </div>

          <div className="border-t border-slate-200 pt-3 dark:border-slate-800 flex items-center justify-between text-xs">
            <Link
              href="/login"
              className="flex items-center gap-1 text-slate-500 hover:text-slate-900 dark:text-slate-400 dark:hover:text-white"
            >
              <ArrowLeft size={13} />
              <span>Back to login</span>
            </Link>
            <span className="text-slate-400">Hardware token priority</span>
          </div>
        </div>
      </main>
    </div>
  )
}
