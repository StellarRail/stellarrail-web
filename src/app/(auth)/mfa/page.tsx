'use client'
import { useEffect, useState } from 'react'
import { useRouter } from 'next/navigation'
import { KeyRound, ShieldCheck, AlertCircle, ArrowLeft } from 'lucide-react'
import { mfaRequest } from '@/features/auth/api'
import { useAuthStore } from '@/stores/auth-store'
import { Input } from '@/components/ui/input'
import { Button } from '@/components/ui/button'

export default function MfaPage(): React.JSX.Element {
  const [code, setCode] = useState('')
  const [err, setErr] = useState('')
  const [attempts, setAttempts] = useState(0)
  const [cooldown, setCooldown] = useState(0)
  const router = useRouter()

  useEffect(() => {
    if (code.length === 6) {
      void (async () => {
        try {
          const r = await mfaRequest(code)
          useAuthStore.getState().setSession(r.user, r.accessToken, r.expiresIn)
          const role = r.user.role
          router.push(role === 'admin' ? '/admin/users' : role === 'approver' ? '/approvals' : '/')
        } catch (e) {
          const n = attempts + 1
          setAttempts(n)
          setErr(e instanceof Error ? e.message : 'Invalid code')
          if (n >= 3) setErr('Too many attempts — account locked for 5 minutes')
          else setCooldown(30)
        }
      })()
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [code])

  useEffect(() => {
    if (cooldown <= 0) return
    const t = setInterval(() => setCooldown((c) => Math.max(0, c - 1)), 1000)
    return () => clearInterval(t)
  }, [cooldown])

  return (
    <div className="relative flex min-h-[100dvh] items-center justify-center bg-canvas p-4 transition-colors dark:bg-navy-950">
      <div className="absolute inset-0 rail-pattern opacity-40 pointer-events-none" />

      <main className="relative z-10 w-full max-w-md animate-item-reveal">
        <div className="mb-6 flex flex-col items-center text-center">
          <div className="flex h-12 w-12 items-center justify-center rounded-2xl bg-navy-900 text-white shadow-md dark:bg-stellar-500 dark:text-navy-950 mb-3">
            <KeyRound size={22} strokeWidth={2} />
          </div>
          <span className="font-mono text-[10px] font-bold uppercase tracking-widest text-slate-600 dark:text-slate-400">
            Cryptographic Multi-Factor
          </span>
          <h1 className="mt-1 text-2xl font-bold tracking-tight text-ink dark:text-white font-display">
            Two-factor authentication
          </h1>
          <p className="mt-1 text-xs text-slate-600 dark:text-slate-400">
            Enter the 6-digit TOTP security code generated by your authenticator hardware or app.
          </p>
        </div>

        <div className="rounded-2xl border border-line/80 bg-white p-7 shadow-subtle dark:border-white/10 dark:bg-navy-900/90 backdrop-blur-md">
          <div className="space-y-4">
            <div>
              <Input
                aria-label="6-digit code"
                inputMode="numeric"
                maxLength={6}
                value={code}
                autoFocus
                placeholder="000 000"
                onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
                className="h-12 text-center font-mono text-xl tracking-[0.4em] font-bold"
              />

              {err ? (
                <div
                  role="alert"
                  className="mt-2.5 flex items-center gap-1.5 rounded-lg border border-rose-300 bg-rose-50 p-2.5 text-xs text-rose-800 dark:border-rose-900 dark:bg-rose-950/60 dark:text-rose-300 font-mono"
                >
                  <AlertCircle size={14} className="shrink-0" />
                  <span>{err}</span>
                </div>
              ) : null}
            </div>

            <div className="flex items-center justify-between text-xs font-mono text-slate-600 dark:text-slate-400">
              <span>Security threshold:</span>
              <span className="font-semibold text-ink dark:text-slate-200">
                Attempts: {attempts}/3
              </span>
            </div>

            <Button
              disabled={cooldown > 0}
              onClick={() => setCooldown(30)}
              variant="outline"
              className="tactile-btn w-full"
            >
              {cooldown > 0 ? `Resend in ${cooldown}s` : 'Resend code'}
            </Button>

            <div className="border-t border-line/60 pt-4 dark:border-white/5 flex items-center justify-between text-xs">
              <a
                href="/login"
                className="flex items-center gap-1 text-slate-600 hover:text-ink dark:text-slate-400 dark:hover:text-white"
              >
                <ArrowLeft size={13} />
                <span>Back to login</span>
              </a>
              <a
                href="/login"
                className="font-medium text-sky-700 hover:underline dark:text-sky-400"
              >
                Use a backup code
              </a>
            </div>
          </div>
        </div>
      </main>
    </div>
  )
}
